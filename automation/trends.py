#!/usr/bin/env python3
"""Ledger for marketing trends found by /trends. Standard library only. Makes no network calls.

  python automation/trends.py add --claim "..." --source-name "..." --url https://... --published 2026-10-01 \
        --kind {expert-opinion,data,vendor-claim} [--expert "Name"] [--applies outreach,personas] [--notes "..."]
  python automation/trends.py list [--status new|adopted|rejected] [--stale]
  python automation/trends.py decide ID --decision {adopt,reject} [--confirmed-by-user]
  python automation/trends.py render        rewrite playbook/13-supplement-marketing-trends.md from ADOPTED entries only

Ledger: trends/trends.json (local, git-ignored). Rules: every entry needs a real URL, a source name, a publish date and a kind.
The agent may add (status new) and reject. ADOPT changes what the other commands read, so it needs --confirmed-by-user.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEDGER = os.path.join(ROOT, "trends", "trends.json")
PLAYBOOK = os.path.join(ROOT, "playbook", "13-supplement-marketing-trends.md")
KINDS = ("expert-opinion", "data", "vendor-claim")
STALE_DAYS = 180
MAX_CLAIM = 300


def load(path=None):
    path = path or LEDGER
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save(entries, path=None):
    path = path or LEDGER
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(entries, f, indent=2, ensure_ascii=False)
        f.write("\n")


def entry_id(url, claim):
    key = re.sub(r"\s+", " ", claim.lower().strip()) + "|" + url.strip().lower().rstrip("/")
    return hashlib.sha1(key.encode("utf-8")).hexdigest()[:8]


def validate(claim, source_name, url, published, kind):
    problems = []
    if not claim or not claim.strip():
        problems.append("claim is empty")
    elif len(claim) > MAX_CLAIM:
        problems.append(f"claim is over {MAX_CLAIM} characters; paraphrase one idea")
    if not source_name or not source_name.strip():
        problems.append("source name is required")
    if not re.match(r"^https?://[^\s/]+\.[^\s/]+", url or ""):
        problems.append("a real http(s) URL is required")
    try:
        d = datetime.date.fromisoformat(published)
        if d > datetime.date.today():
            problems.append("published date is in the future")
    except (TypeError, ValueError):
        problems.append("published must be a date like 2026-10-01")
    if kind not in KINDS:
        problems.append("kind must be one of: " + ", ".join(KINDS))
    return problems


def is_stale(entry, today=None):
    today = today or datetime.date.today()
    try:
        return (today - datetime.date.fromisoformat(entry["published"])).days > STALE_DAYS
    except (KeyError, ValueError):
        return True


def add(entries, claim, source_name, url, published, kind, expert="", applies=(), notes="", today=None):
    """Return (entry_or_None, message)."""
    problems = validate(claim, source_name, url, published, kind)
    if problems:
        return None, "REFUSED: " + "; ".join(problems)
    eid = entry_id(url, claim)
    if any(e["id"] == eid for e in entries):
        return None, f"Already tracked ({eid})."
    e = {
        "id": eid, "claim": claim.strip(), "source_name": source_name.strip(), "url": url.strip(),
        "published": published, "kind": kind, "expert": expert.strip(),
        "applies_to": [a.strip() for a in applies if a.strip()], "notes": notes.strip(),
        "added": (today or datetime.date.today()).isoformat(), "status": "new",
    }
    entries.append(e)
    return e, f"Added {eid} as new (not used by any command until you adopt it)."


def decide(entries, eid, decision, confirmed=False):
    for e in entries:
        if e["id"] == eid:
            if decision == "adopt":
                if not confirmed:
                    return "REFUSED: adopting changes what the commands read. Ask the user, then re-run with --confirmed-by-user."
                if e["kind"] == "vendor-claim" and "vendor" not in e["notes"].lower():
                    e["notes"] = (e["notes"] + " Vendor claim: directional only.").strip()
                e["status"] = "adopted"
            else:
                e["status"] = "rejected"
            return f"{eid} -> {e['status']}."
    return f"REFUSED: no trend with id {eid}."


def render(entries):
    adopted = [e for e in entries if e["status"] == "adopted"]
    lines = [
        "# 13 SUPPLEMENT: Marketing trends (NOT from the course)",
        "Generated by `automation/trends.py render` from trends the user ADOPTED. Do not edit by hand; run `/trends` instead.",
        "Each line is something a named source said, with its date. These are hypotheses to test, not facts about your market.",
        "Where this conflicts with the course (playbooks 01-07, 10), the course wins.",
        "",
    ]
    if not adopted:
        lines.append("_No adopted trends yet. Run `/trends` to research some, then adopt the ones you trust._")
    groups = {}
    for e in adopted:
        for tag in (e["applies_to"] or ["general"]):
            groups.setdefault(tag, []).append(e)
    for tag in sorted(groups):
        lines.append(f"## {tag}")
        for e in sorted(groups[tag], key=lambda x: x["published"], reverse=True):
            who = f"{e['expert']}, " if e.get("expert") else ""
            flag = " **[STALE: re-verify]**" if is_stale(e) else ""
            lines.append(f"- {e['claim']} ({e['kind']}; {who}{e['source_name']}, {e['published']}; {e['url']}){flag}")
            if e.get("notes"):
                lines.append(f"  - note: {e['notes']}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add")
    a.add_argument("--claim", required=True)
    a.add_argument("--source-name", required=True)
    a.add_argument("--url", required=True)
    a.add_argument("--published", required=True)
    a.add_argument("--kind", required=True)
    a.add_argument("--expert", default="")
    a.add_argument("--applies", default="")
    a.add_argument("--notes", default="")
    ls = sub.add_parser("list")
    ls.add_argument("--status")
    ls.add_argument("--stale", action="store_true")
    d = sub.add_parser("decide")
    d.add_argument("id")
    d.add_argument("--decision", required=True, choices=["adopt", "reject"])
    d.add_argument("--confirmed-by-user", action="store_true")
    sub.add_parser("render")
    args = ap.parse_args(argv)

    entries = load()
    if args.cmd == "add":
        e, msg = add(entries, args.claim, args.source_name, args.url, args.published, args.kind,
                     args.expert, args.applies.split(","), args.notes)
        if e:
            save(entries)
        print(msg)
        return 0 if e or msg.startswith("Already") else 1
    if args.cmd == "list":
        shown = [e for e in entries if (not args.status or e["status"] == args.status) and (not args.stale or is_stale(e))]
        for e in shown:
            print(f"{e['id']} [{e['status']}{', STALE' if is_stale(e) else ''}] {e['claim']} ({e['kind']}, {e['source_name']}, {e['published']})")
        print(f"{len(shown)} shown, {len(entries)} total")
        return 0
    if args.cmd == "decide":
        msg = decide(entries, args.id, args.decision, args.confirmed_by_user)
        if not msg.startswith("REFUSED"):
            save(entries)
            with open(PLAYBOOK, "w", encoding="utf-8", newline="\n") as f:
                f.write(render(entries))
        print(msg)
        return 1 if msg.startswith("REFUSED") else 0
    if args.cmd == "render":
        with open(PLAYBOOK, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(entries))
        print(f"Wrote {PLAYBOOK} ({sum(e['status'] == 'adopted' for e in entries)} adopted trends)")
        return 0


if __name__ == "__main__":
    sys.exit(main())
